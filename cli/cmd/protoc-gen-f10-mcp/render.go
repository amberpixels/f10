package main

import (
	"path"
	"strconv"

	"google.golang.org/protobuf/compiler/protogen"
)

var (
	connectPkg = protogen.GoImportPath("connectrpc.com/connect")
	contextPkg = protogen.GoImportPath("context")
	protoPkg   = protogen.GoImportPath("google.golang.org/protobuf/proto")
)

// render writes the Tool type and one entry per tool. Each entry calls its
// method through the generated Connect client, so dispatch stays typed.
func render(g *protogen.GeneratedFile, tools []tool) error {
	ctx := g.QualifiedGoIdent(contextPkg.Ident("Context"))
	httpClient := g.QualifiedGoIdent(connectPkg.Ident("HTTPClient"))
	clientOption := g.QualifiedGoIdent(connectPkg.Ident("ClientOption"))
	message := g.QualifiedGoIdent(protoPkg.Ident("Message"))

	g.P("// Code generated by protoc-gen-f10-mcp. DO NOT EDIT.")
	g.P()
	g.P("// Package mcptools is every unary API method as an MCP tool, generated from")
	g.P("// the proto schema, so the tool list never drifts from the API.")
	g.P("package mcptools")
	g.P()
	g.P("// A Tool is one API method as an MCP tool.")
	g.P("type Tool struct {")
	g.P("// Name is the method in snake case.")
	g.P("Name string")
	g.P("// Procedure is the Connect route, /<package>.<Service>/<Method>.")
	g.P("Procedure string")
	g.P("// Description is the rpc's comment.")
	g.P("Description string")
	g.P("// InputSchema is the request message as a JSON Schema, with proto field names.")
	g.P("InputSchema string")
	g.P("// NewRequest is an empty request message to read the arguments into.")
	g.P("NewRequest func() ", message)
	g.P("// Call sends req, a NewRequest message, to the API at baseURL.")
	g.P("Call func(ctx ", ctx, ", hc ", httpClient, ", baseURL string, req ", message,
		", opts ...", clientOption, ") (", message, ", error)")
	g.P("}")
	g.P()
	g.P("// Tools is every unary method, in proto file and declaration order.")
	g.P("var Tools = []Tool{")

	for _, t := range tools {
		in := g.QualifiedGoIdent(t.method.Input.GoIdent)
		newClient := g.QualifiedGoIdent(protogen.GoIdent{
			GoName:       "New" + t.service.GoName + "Client",
			GoImportPath: connectImportPath(t.file),
		})

		g.P("{")
		g.P("Name: ", strconv.Quote(t.name), ",")
		g.P("Procedure: ", strconv.Quote(t.procedure), ",")
		g.P("Description: ", strconv.Quote(t.description), ",")
		g.P("InputSchema: ", strconv.Quote(t.schema), ",")
		g.P("NewRequest: func() ", message, " { return &", in, "{} },")
		g.P("Call: func(ctx ", ctx, ", hc ", httpClient, ", baseURL string, req ", message,
			", opts ...", clientOption, ") (", message, ", error) {")
		g.P("res, err := ", newClient, "(hc, baseURL, opts...).", t.method.GoName,
			"(ctx, ", g.QualifiedGoIdent(connectPkg.Ident("NewRequest")), "(req.(*", in, ")))")
		g.P("if err != nil {")
		g.P("return nil, err")
		g.P("}")
		g.P()
		g.P("return res.Msg, nil")
		g.P("},")
		g.P("},")
	}

	g.P("}")

	return nil
}

// connectImportPath is where protoc-gen-connect-go puts f's clients.
func connectImportPath(f *protogen.File) protogen.GoImportPath {
	return protogen.GoImportPath(path.Join(string(f.GoImportPath), string(f.GoPackageName)+"connect"))
}
