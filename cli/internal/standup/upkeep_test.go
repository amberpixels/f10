func files(paths ...string) []File {
	out := make([]File, 0, len(paths))
	for _, p := range paths {
		out = append(out, File{Path: p, Added: 1, Deleted: 1})
	}

	return out
}

func red(h int) *CI { return &CI{Red: true, At: at(h)} }

func TestClassifyCommit(t *testing.T) {
	merge := func(base bool) Commit {
		c := commit("m", "FT-1/a", "Merge branch 'main'", 2)
		c.Parents, c.BaseMerge = []string{"p1", "p2"}, base

		return c
	}

	withFiles := func(fs []File, ci *CI) Commit {
		c := commit("c", "FT-1/a", "x", 2)
		c.Files, c.ParentCI = fs, ci

		return c
	}

	bigTest := []File{{Path: "a_test.go", Added: 20, Deleted: 11}}
	smallTest := []File{{Path: "a_test.go", Added: 20, Deleted: 10}}

	for _, tc := range []struct {
		name   string
		c      Commit
		extra  []string
		reason string // "" is work
	}{
		{"merge of the base", merge(true), nil, UpkeepBaseMerge},
		{"merge of anything else", merge(false), nil, ""},
		{"lockfiles only", withFiles(files("go.sum", "web/yarn.lock"), nil), nil, UpkeepFiles},
		{"lockfile and code", withFiles(files("go.sum", "main.go"), nil), nil, ""},
		{"manifest bump", withFiles(files("go.mod", "go.sum"), nil), nil, ""},
		{"snapshots", withFiles(files("ui/__snapshots__/a.snap", "x/testdata/out.golden"), nil), nil, UpkeepFiles},
		{"generated by attribute", withFiles([]File{{Path: "api/client.go", Generated: true}}, nil), nil, UpkeepFiles},
		{"generated by name", withFiles(files("api/types.pb.go", "api/mock_gen.go"), nil), nil, UpkeepFiles},
		{"project glob", withFiles(files("db/schema.rb"), nil), []string{"db/schema.rb"}, UpkeepFiles},
		{"project glob elsewhere", withFiles(files("app/db/schema.rb"), nil), []string{"db/schema.rb"}, ""},
		{"no files read", withFiles(nil, nil), nil, ""},
		{"test fix after red", withFiles(smallTest, red(1)), nil, UpkeepCIFix},
		{"test fix too big", withFiles(bigTest, red(1)), nil, ""},
		{"test fix after green", withFiles(smallTest, &CI{At: at(1)}), nil, ""},
		{"test fix, CI unknown", withFiles(smallTest, nil), nil, ""},
		{"test fix before red finished", withFiles(smallTest, red(3)), nil, ""},
		{"test and code after red", withFiles(append(files("a.go"), smallTest...), red(1)), nil, ""},
		{"spec dir after red", withFiles(files("spec/models/user_spec.rb", "spec/support/x.rb"), red(1)), nil, UpkeepCIFix},
		{"binary test file after red", withFiles([]File{{Path: "testdata/x.png", Binary: true}}, red(1)), nil, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			class, reason := classifyCommit(tc.c, tc.extra)

			want := ClassWork
			if tc.reason != "" {
				want = ClassUpkeep
			}

			if class != want || reason != tc.reason {
				t.Errorf("= %s %q, want %s %q", class, reason, want, tc.reason)
			}
		})
	}
}

func TestNeedsCI(t *testing.T) {
	c := commit("c", "FT-1/a", "x", 2)

	if c.Files = files("a_test.go"); !NeedsCI(c, nil) {
		t.Error("a small test-only commit needs its parent's CI")
	}

	if c.Files = files("go.sum"); NeedsCI(c, nil) {
		t.Error("a lockfile commit is upkeep already, no CI needed")
	}

	if c.Files = files("a.go"); NeedsCI(c, nil) {
		t.Error("a code commit is work whatever CI said")
	}
}

func TestClassifyPush(t *testing.T) {
	yes, no := true, false

	for _, tc := range []struct {
		same *bool
		want string
	}{{&yes, ClassUpkeep}, {&no, ClassWork}, {nil, ClassWork}} {
		if got, _ := classifyPush(ForcePush{SamePatches: tc.same}); got != tc.want {
			t.Errorf("same patches %v = %s, want %s", tc.same, got, tc.want)
		}
	}
}

func TestGlob(t *testing.T) {
	for _, tc := range []struct {
		pattern, path string
		want          bool
	}{
		{"go.sum", "go.sum", true},
		{"go.sum", "tools/go.sum", true},
		{"*.snap", "a/b/c.snap", true},
		{"db/schema.rb", "db/schema.rb", true},
		{"db/schema.rb", "x/db/schema.rb", false},
		{"**/spec/**", "spec/a_spec.rb", true},
		{"**/spec/**", "engines/x/spec/a.rb", true},
		{"**/spec/**", "spec", false},
		{"api/**/*.gen.ts", "api/v1/users.gen.ts", true},
		{"api/**/*.gen.ts", "api/users.gen.ts", true},
		{"api/**/*.gen.ts", "web/api/users.gen.ts", false},
	} {
		if got := Glob(tc.pattern, tc.path); got != tc.want {
			t.Errorf("Glob(%q, %q) = %v, want %v", tc.pattern, tc.path, got, tc.want)
		}
	}

	for _, bad := range []string{"", "/db/schema.rb", "db/[schema.rb"} {
		if CheckGlob(bad) == nil {
			t.Errorf("CheckGlob(%q) passed", bad)
		}
	}

	if err := CheckGlob("api/**/*.gen.ts"); err != nil {
		t.Errorf("CheckGlob refused a good glob: %v", err)
	}
}

// A task whose period holds only upkeep folds; one work item, or opening
// or merging a PR, keeps it work. A rebase-only PR is reported at all.
func TestGroupClassifiesTasks(t *testing.T) {
	yes := true
	rebase := func(p *HostPR) {
		p.CreatedAt = since.Add(-48 * time.Hour)
		p.ForcePushes = []ForcePush{
			{At: at(2), Before: "b0", After: "b1", SamePatches: &yes},
			{At: since.Add(-time.Hour), Before: "a0", After: "b0"},
		}
	}

	baseMerge := commit("m2", "FT-2/b", "Merge main", 3)
	baseMerge.Parents, baseMerge.BaseMerge = []string{"p1", "p2"}, true

	lock := commit("l3", "FT-3/c", "bump", 3)
	lock.Files = files("go.sum")

	code := commit("w2", "FT-2/b", "work", 4)
	code.Files = files("main.go")

	in := input([]Commit{baseMerge, lock}, []HostPR{
		own(1, "FT-1/a", "main", HostOpen, rebase),
		own(2, "FT-2/b", "main", HostOpen, func(p *HostPR) { p.CreatedAt = since.Add(-48 * time.Hour) }),
		own(4, "FT-4/d", "main", HostOpen, rebase, func(p *HostPR) { p.CreatedAt = at(1) }),
	})
	r := Group(in)

	t1 := taskByID(t, r, "FT-1")
	if t1.Class != ClassUpkeep || len(t1.PRs) != 1 || len(t1.PRs[0].ForcePushes) != 1 ||
		t1.PRs[0].ForcePushes[0].Upkeep != UpkeepRebase {
		t.Errorf("FT-1 = %+v, want an upkeep task with one rebase in the period", t1)
	}

	if t2 := taskByID(t, r, "FT-2"); t2.Class != ClassUpkeep || t2.PRs[0].Commits[0].Upkeep != UpkeepBaseMerge {
		t.Errorf("FT-2 = %+v, want upkeep: a base merge only", t2)
	}

	if t3 := taskByID(t, r, "FT-3"); t3.Class != ClassUpkeep || t3.Commits[0].Upkeep != UpkeepFiles {
		t.Errorf("FT-3 = %+v, want upkeep: a lockfile commit only", t3)
	}

	if t4 := taskByID(t, r, "FT-4"); t4.Class != ClassWork {
		t.Errorf("FT-4 = %+v, want work: the PR opened in the period", t4)
	}

	in.Commits = append(in.Commits, code)
	if t2 := taskByID(t, Group(in), "FT-2"); t2.Class != ClassWork {
		t.Errorf("FT-2 with a code commit = %s, want work", t2.Class)
	}
}
